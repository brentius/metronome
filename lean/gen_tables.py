"""Generate Metronome/Machine/Tables.lean from code/md2/machine.json (the source SPEC_V2 names for every number).

Usage:  python gen_tables.py           write the file
        python gen_tables.py --check   exit 1 if the file is missing or stale

The generated module (namespace Metronome.Machine.Tables) carries names and numbers only: sizes, instruction fields,
jump modes and move-guard codes, SRC/DST/GUARD/JUMP_GUARDS/TRIGGERS name tables (index = encoding), write groups,
pin names, configuration inventory, host map bases, strides and every register offset/size/access. Semantics live in
the hand-written modules.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[0]
SRC = ROOT / "code" / "md2" / "machine.json"
OUT = HERE / "Metronome" / "Machine" / "Tables.lean"


def ident(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


def lstr(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def arr(items) -> str:
    return "#[" + ", ".join(items) + "]"


def render(d: dict) -> str:
    o: list[str] = []
    w = o.append
    w("/-")
    w("GENERATED by lean/gen_tables.py from code/md2/machine.json. Do not edit.")
    w("Regenerate: python lean/gen_tables.py   (check: --check)")
    w("SPEC_V2 preamble: names and numbers come from machine.py and its generated tables.")
    w("-/")
    w("")
    w("namespace Metronome.Machine.Tables")
    w("")
    w(f"def VERSION : Nat := {d['version']}")
    w("")
    w("-- sizes (machine.py)")
    for k, v in d["sizes"].items():
        if k == "VERSION":
            continue
        w(f"def {ident(k)} : Nat := {v}")
    w("")
    w("-- instruction fields: (lsb, width)")
    for k, (lsb, wd) in d["fields"].items():
        w(f"def FIELD_{ident(k)} : Nat × Nat := ({lsb}, {wd})")
    w("")
    w("-- jump modes (on jcond) and move guards (on cond)")
    for k, v in d["jmodes"].items():
        w(f"def JMODE_{ident(k)} : Nat := {v}")
    for k, v in d["guards"].items():
        w(f"def MGUARD_{ident(k)} : Nat := {v}")
    w("")
    for key, nm in [("src", "srcNames"), ("dst", "dstNames"), ("guard_conds", "guardNames"),
                    ("jump_guards", "jumpGuardNames"), ("triggers", "triggerNames"),
                    ("in_pins", "inPinNames"), ("out_pins", "outPinNames")]:
        w(f"def {nm} : Array String := {arr(lstr(x) for x in d[key])}")
    w("")
    w("-- write groups: (group name, member destination names)")
    w("def writeGroups : Array (String × Array String) := #[")
    items = list(d["write_groups"].items())
    for i, (g, ms) in enumerate(items):
        w(f"  ({lstr(g)}, {arr(lstr(m) for m in ms)})" + ("," if i < len(items) - 1 else ""))
    w("]")
    w("")
    w("-- host link pins")
    w("def hostPins : Array (String × String) := " + arr(f"({lstr(k)}, {lstr(v)})" for k, v in d["host_pins"].items()))
    w("")
    w("-- configuration latch inventory: (block, instances, [(field, bits)])")
    w("def configBlocks : Array (String × Nat × Array (String × Nat)) := #[")
    items = list(d["config_blocks"].items())
    for i, (b, v) in enumerate(items):
        fs = arr(f"({lstr(f)}, {n})" for f, n in v["fields"].items())
        w(f"  ({lstr(b)}, {v['instances']}, {fs})" + ("," if i < len(items) - 1 else ""))
    w("]")
    w(f"def CONFIG_BITS_TOTAL : Nat := {d['config_bits_total']}")
    w("")
    w("-- host map bases and strides")
    for k, v in d["host_map"].items():
        w(f"def {ident(k)} : Nat := 0x{v:04X}")
    for k, v in d["host_stride"].items():
        w(f"def STRIDE_{ident(k)} : Nat := 0x{v:X}")
    w("")
    w("-- host register blocks: (block, base, stride, instances, [(offset, name, bytes, access)])")
    w("def hostBlocks : Array (String × Nat × Nat × Nat × Array (Nat × String × Nat × String)) := #[")
    items = list(d["host_blocks"].items())
    for i, (b, v) in enumerate(items):
        regs = arr(f"(0x{int(off, 16):02X}, {lstr(r[0])}, {r[1]}, {lstr(r[2])})" for off, r in v["regs"].items())
        w(f"  ({lstr(b)}, 0x{v['base']:04X}, 0x{v['stride']:X}, {v['instances']}, {regs})"
          + ("," if i < len(items) - 1 else ""))
    w("]")
    w("")
    w("-- register offsets within a block instance, and byte widths")
    for b, v in d["host_blocks"].items():
        for off, r in v["regs"].items():
            w(f"def {ident(b)}_{ident(r[0])} : Nat := 0x{int(off, 16):02X}")
            w(f"def {ident(b)}_{ident(r[0])}_BYTES : Nat := {r[1]}")
    w("")
    w("end Metronome.Machine.Tables")
    return "\n".join(o) + "\n"


def main() -> int:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    text = render(d)
    if "--check" in sys.argv[1:]:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        if cur != text:
            print(f"STALE: {OUT} differs from generator output; run python {Path(__file__).name}")
            return 1
        print(f"OK: {OUT.name} is current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
