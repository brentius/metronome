"""Generate the configuration-latch probe for a gate-level netlist of tt_um_brentius_metronome.

    python gen_cfg_probe.py NETLIST OUT_DIR

Writes OUT_DIR/cfg_probe.vh (included by tb.v under CFG_PROBE) and OUT_DIR/cfg_probe.json.

The netlist keeps cfg_latch_bank's instance names flattened: latch `u_cfg.g_byte[k].g_bit[b].u_l`
(sg13cmos5l_dlhrq_1) holds configuration bit 8k+b, and clock gate `u_cfg.g_byte[k].u_cg` (sg13cmos5l_lgcp_1)
strobes byte k. Synthesis removes latches whose bits are unused, so the probe covers the latches that exist.

cfg_probe.vh declares:
  - `cfg_probe[8*BYTES-1:0]`: each existing latch's Q net (absent bits read 0);
  - one `cfg_latch_chk` per latch on its own D, GATE and Q nets (timing checks Icarus does not enforce);
  - one `cfg_gate_cnt` per clock gate on its GCLK output (strobe count per byte).
cfg_probe.json lists the existing bit indices, the bytes with a clock gate, and the hierarchical net names used.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

CFG_BYTES = 56
INST = re.compile(r"(sg13cmos5l_dlhrq_1|sg13cmos5l_lgcp_1)\s+(\\\S+|\S+)\s*\((.*?)\);", re.S)
PIN = re.compile(r"\.(\w+)\s*\(\s*(\\\S+\s|[^\s()]+)\s*\)")
LATCH = re.compile(r"^\\?u_cfg\.g_byte\[(\d+)\]\.g_bit\[(\d+)\]\.u_l$")
GATE = re.compile(r"^\\?u_cfg\.g_byte\[(\d+)\]\.u_cg$")


def ref(net: str) -> str:
    """Hierarchical reference from the testbench to a top-level net of the netlist."""
    net = net.strip()
    return f"user_project.{net} " if net.startswith("\\") else f"user_project.{net}"


def main() -> int:
    netlist, out = Path(sys.argv[1]), Path(sys.argv[2])
    text = netlist.read_text()
    latches: dict[int, dict[str, str]] = {}
    gates: dict[int, str] = {}
    for cell, name, body in INST.findall(text):
        pins = {p: n for p, n in PIN.findall(body)}
        if cell == "sg13cmos5l_dlhrq_1":
            m = LATCH.match(name.strip())
            assert m, f"unexpected latch instance {name!r}"
            latches[8 * int(m[1]) + int(m[2])] = pins
        else:
            m = GATE.match(name.strip())
            assert m, f"unexpected clock gate instance {name!r}"
            gates[int(m[1])] = pins["GCLK"]
    assert latches, "no configuration latches found"
    nbits = 8 * CFG_BYTES
    o = [f"// GENERATED by gen_cfg_probe.py from {netlist.name}: {len(latches)} latches, {len(gates)} clock gates.",
         f"wire [{nbits - 1}:0] cfg_probe;"]
    for n in range(nbits):
        o.append(f"assign cfg_probe[{n}] = {ref(latches[n]['Q'])};" if n in latches
                 else f"assign cfg_probe[{n}] = 1'b0;")
    for n, p in sorted(latches.items()):
        o.append(f"cfg_latch_chk u_chk_{n} (.d({ref(p['D'])}), .g({ref(p['GATE'])}), .q({ref(p['Q'])}));")
    for k, g in sorted(gates.items()):
        o.append(f"cfg_gate_cnt u_gck_{k} (.g({ref(g)}));")
    out.mkdir(parents=True, exist_ok=True)
    (out / "cfg_probe.vh").write_text("\n".join(o) + "\n")
    (out / "cfg_probe.json").write_text(json.dumps({
        "netlist": str(netlist), "bits": sorted(latches), "gated_bytes": sorted(gates),
        "q_nets": {n: p["Q"].strip() for n, p in latches.items()}}, indent=1))
    print(f"{len(latches)} latches, {len(gates)} clock gates -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
