"""Generate the v2 RTL's include files in src/ from code/md2/machine.py (the single source of v2 numbers).

    python code/tests/rtl_v2/gen_rtl_tables.py           # write src/md2_defs.vh and src/md2_map.vh
    python code/tests/rtl_v2/gen_rtl_tables.py --check   # fail if either is stale

src/md2_defs.vh is a byte-for-byte copy of code/md2/md2_defs.vh (the Tiny Tapeout flow reads only src/).
src/md2_map.vh adds what md2_defs.vh does not carry: host-map bases, strides and register offsets (machine.HOST_MAP,
HOST_STRIDE, *_REGS), the configuration window with a per-bit mask of the latches that exist, and the write-group
number of every destination port (machine.WRITE_GROUPS).

The per-register bit masks below are the only hand-entered layout: machine.py states register layouts as text.
They are checked against machine.CONFIG_BITS_TOTAL and per block against machine.CONFIG_BITS.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
_spec = importlib.util.spec_from_file_location("md2_machine_gen", ROOT / "code/md2/machine.py")
m = importlib.util.module_from_spec(_spec)
sys.modules["md2_machine_gen"] = m
_spec.loader.exec_module(m)

# used bits per byte of each configuration register (layouts from machine.*_REGS descriptions)
REG_MASK = {
    ("LINE", "INC"): [0xFF, 0xFF], ("LINE", "MOD"): [0xFF, 0xFF], ("LINE", "T0"): [0xFF, 0xFF],
    ("LINE", "T1"): [0xFF, 0xFF], ("LINE", "T2"): [0xFF, 0xFF], ("LINE", "PRE"): [0xFF, 0xFF],
    ("LINE", "WLO"): [0xFF, 0xFF], ("LINE", "WHI"): [0xFF, 0xFF],
    ("LINE", "EDGE"): [0xFF], ("LINE", "T0EDGE"): [0x7F], ("LINE", "PINS"): [0xFF], ("LINE", "SNAP"): [0x03],
    ("LINE", "LUT0"): [0xFF] * 4, ("LINE", "LUT1"): [0xFF] * 4, ("LINE", "HOLD"): [0xFF],
    ("THREAD", "CFG"): [0xFF], ("THREAD", "W0C"): [0x3F], ("THREAD", "W1C"): [0x3F],
    ("THREAD", "W0H"): [0xFF], ("THREAD", "W1H"): [0xFF],
    ("LFSR", "POLY"): [0xFF] * 4,
    ("STREAM", "MODE"): [0x03], ("STREAM", "START"): [0xFF, 0x07], ("STREAM", "LEN"): [0xFF, 0x0F],
    ("STREAM", "MARK"): [0xFF, 0x0F],
    ("OUT", "BIND"): [0x1F], ("OUT", "SEL"): [0x3F], ("OUT", "LUT"): [0xFF] * 4, ("OUT", "OE"): [0xFF] * 4,
}
CFG_BLOCKS = ["LINE", "THREAD", "LFSR", "STREAM", "OUT"]
CFG_BITS_KEY = {"LINE": ["line"], "THREAD": ["thread"], "LFSR": ["lfsr"], "STREAM": ["stream"], "OUT": ["out", "oe"]}


def _block_geom(b):
    base, st, n, regs = m.HOST_BLOCKS[b]
    return m.HOST_MAP[base], (m.HOST_STRIDE[st] if st else 0x10), n, regs


def cfg_window():
    lo = min(_block_geom(b)[0] for b in CFG_BLOCKS)
    hi = max(_block_geom(b)[0] + _block_geom(b)[1] * _block_geom(b)[2] for b in CFG_BLOCKS)
    mask = bytearray(hi - lo)
    per = {}
    for b in CFG_BLOCKS:
        base, stride, n, regs = _block_geom(b)
        tot = 0
        for i in range(n):
            for off, (name, nb, acc, _) in regs.items():
                assert acc == "W", (b, name)
                if b == "OUT" and name == "OE" and i >= m.N_OE_PINS:
                    continue
                bm = REG_MASK[(b, name)]
                assert len(bm) == nb, (b, name)
                for k, v in enumerate(bm):
                    a = base + stride * i + off + k - lo
                    assert mask[a] == 0
                    mask[a] = v
                    tot += bin(v).count("1")
        want = sum(m.CONFIG_BITS[k] for k in CFG_BITS_KEY[b])
        assert tot == want, f"{b}: {tot} latch bits, machine.CONFIG_BITS says {want}"
        per[b] = tot
    assert sum(bin(v).count("1") for v in mask) == m.CONFIG_BITS_TOTAL
    return lo, mask


def gen_map() -> str:
    L = ["// GENERATED by code/tests/rtl_v2/gen_rtl_tables.py from code/md2/machine.py. Do not edit.",
         "`ifndef MD2_MAP_VH", "`define MD2_MAP_VH", ""]
    L.append("// host map bases and strides (machine.HOST_MAP, HOST_STRIDE)")
    for k, v in m.HOST_MAP.items():
        L.append(f"localparam [15:0] HA_{k} = 16'h{v:04X};")
    for k, v in m.HOST_MAP.items():
        L.append(f"localparam integer HAI_{k} = {v};")
    for k, v in m.HOST_STRIDE.items():
        L.append(f"localparam integer HS_{k} = {v};")
    L.append("// 16-bit span of each block (stride x instances)")
    for b, (base, st, n, regs) in m.HOST_BLOCKS.items():
        span = (m.HOST_STRIDE[st] if st else 0x10) * n
        L.append(f"localparam [15:0] HSPAN_{b} = 16'h{span:04X};")
    L.append(f"localparam [15:0] HSPAN_PROG = 16'h{m.HOST_STRIDE['PROG_CORE'] * m.N_CORES:04X};")
    L.append(f"localparam [15:0] HSPAN_DATA = 16'h{m.DATA_BYTES:04X};")
    L.append("")
    L.append("// register offsets within a block (machine.*_REGS); HO_<block>_<reg>")
    for b, (_, _, _, regs) in m.HOST_BLOCKS.items():
        for off, (name, nb, acc, _) in regs.items():
            L.append(f"localparam integer HO_{b}_{name} = {off};   // {nb} byte(s), {acc}")
    L.append("")
    lo, mask = cfg_window()
    L.append("// configuration window: host bytes CFG_LO .. CFG_LO + CFG_BYTES - 1; CFG_MASK bit 8a+b = latch exists")
    L.append(f"localparam [15:0] CFG_LO = 16'h{lo:04X};")
    L.append(f"localparam integer CFG_LO_I = {lo};")
    L.append(f"localparam integer CFG_BYTES = {len(mask)};")
    L.append(f"localparam [15:0] HSPAN_CFG = 16'h{len(mask):04X};")
    L.append(f"localparam integer CFG_LATCH_BITS = {m.CONFIG_BITS_TOTAL};")
    hexs = "".join(f"{v:02X}" for v in reversed(mask))
    L.append(f"localparam [{8 * len(mask) - 1}:0] CFG_MASK = {8 * len(mask)}'h{hexs};")
    L.extend(["", "// Decode configured bytes, excluding unimplemented gaps and output-only OE.",
              "function cfg_address_is_live;", "    input [15:0] address;"])
    terms = []
    for b in CFG_BLOCKS:
        base, stride, n, _ = _block_geom(b)
        assert stride & (stride - 1) == 0 and base % stride == 0
        offsets = (stride - 1).bit_length()
        sections = [(0, n)] if b != "OUT" else [(0, m.N_OE_PINS), (m.N_OE_PINS, n)]
        for first, limit in sections:
            name = f"CFG_VALID_{b}_{first}"
            lo_addr, hi_addr = base + stride * first, base + stride * limit
            pattern = sum(bool(mask[lo_addr + j - lo]) << j for j in range(stride))
            L.append(f"    localparam [{stride - 1}:0] {name} = {stride}'h{pattern:X};")
            terms.append(f"(address >= 16'h{lo_addr:04X} && address < 16'h{hi_addr:04X}"
                         + f" && {name}[address[{offsets - 1}:0]])")
    L.append("    begin")
    L.append("        cfg_address_is_live = " + " ||\n                              ".join(terms) + ";")
    L.extend(["    end", "endfunction"])
    L.append("")
    L.append("// table sizes")
    L.append(f"localparam integer MD_N_SRC = {len(m.SRC)};")
    L.append(f"localparam integer MD_N_DST = {len(m.DST)};")
    L.append(f"localparam integer MD_N_GUARD = {len(m.GUARD_CONDS)};")
    L.append(f"localparam integer MD_N_TRIG = {len(m.TRIGGERS)};")
    L.append("")
    L.append("// write groups (machine.WRITE_GROUPS): DG_<group>; DG_MAP entry d (bits 5d+4:5d) = group of destination d")
    groups = list(m.WRITE_GROUPS)
    assert len(groups) < 31
    gid = {}
    for i, g in enumerate(groups):
        nm = g.replace(".", "_")
        L.append(f"localparam [4:0] DG_{nm} = 5'd{i};")
        for d in m.WRITE_GROUPS[g]:
            gid[d] = i
    L.append("localparam [4:0] DG_NONE = 5'd31;")
    ent = [gid.get(m.DST[d].name, 31) if d < len(m.DST) else 31 for d in range(64)]
    L.append("localparam [319:0] DG_MAP = {" + ", ".join(f"5'd{e}" for e in reversed(ent)) + "};")
    L.append("")
    L.append("`endif")
    return "\n".join(L) + "\n"


def main(argv):
    check = "--check" in argv
    outs = {ROOT / "src/md2_defs.vh": (ROOT / "code/md2/md2_defs.vh").read_text(encoding="utf-8"),
            ROOT / "src/md2_map.vh": gen_map()}
    stale = []
    for p, txt in outs.items():
        cur = p.read_text(encoding="utf-8") if p.exists() else None
        if cur != txt:
            stale.append(p)
            if not check:
                p.write_text(txt, encoding="utf-8", newline="\n")
    if check and stale:
        print("stale:", *[str(p.relative_to(ROOT)) for p in stale])
        return 1
    print(("checked" if check else "wrote"), *[str(p.relative_to(ROOT)) for p in outs])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
