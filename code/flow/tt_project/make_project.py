"""Superseded for v2.0 by the template layout at the repository root (info.yaml, src/config.json; D18). Kept for
the v1.0 RunPod flow.

Assemble the Tiny Tapeout project for tt_um_brentius_metronome (IHP SG13CMOS5L, 8x4 tiles) from src.

    python code/flow/tt_project/make_project.py OUTDIR [--period 16.667] [--density 60] [--tgz OUT.tgz]

OUTDIR gets the template layout tt_tool.py expects: info.yaml, docs/info.md, src/*.v (RTL, generated header,
SRAM black boxes), src/config.json, src/pdn_cfg.tcl, and the SRAM power-stripe LibreLane plugin at the root.
Vendored PDN files: see vendor/PROVENANCE.md.

Floorplan (die 1724.16 x 710.64 um; TT pins are on the top edge at x ~ 118..191 um):
  * data RAM  RM_IHPSG13_1P_512x32 (416.64 x 191.34): bottom-left, FS (pins face up into the logic).
  * program RAM core 0  RM_IHPSG13_1P_256x64 (784.48 x 118.78): bottom-right, FS.
  * program RAM core 1: top-right, N (pins face down), same x as core 0 so their Metal4 power columns line up.
  x positions are 3.36 + n * 11.24 um (the macro power-column pitch, see the vendored README notes).
"""
