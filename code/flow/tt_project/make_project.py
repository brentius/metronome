def blackboxes() -> str:
    out = ["// Black boxes of the IHP SRAM macros for synthesis and lint (layout from the PDK via MACROS).",
           "`default_nettype none", "/* verilator lint_off UNDRIVEN */", "/* verilator lint_off UNUSEDSIGNAL */"]
    for name, a, d in (("RM_IHPSG13_1P_256x64_c2_bm_bist", 7, 63), ("RM_IHPSG13_1P_512x32_c2_bm_bist", 8, 31)):
        out += ["(* blackbox *)", f"module {name} (", BB_PORTS.format(a=a, d=d), ");", "endmodule"]
    out += ["/* verilator lint_on UNUSEDSIGNAL */", "/* verilator lint_on UNDRIVEN */", "`default_nettype wire", ""]
    return "\n".join(out)


