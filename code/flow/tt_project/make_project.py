def build(out: Path, period: float, density: int) -> None:
    if out.exists():
        shutil.rmtree(out)
    (out / "src").mkdir(parents=True)
    (out / "docs").mkdir()
    (out / "test").mkdir()
    files = sorted(p.name for p in RTL.glob("*.v"))
    for f in files:
        shutil.copy(RTL / f, out / "src" / f)
    shutil.copy(RTL / "md_defs.vh", out / "src/md_defs.vh")
    (out / "src/sram_bb.v").write_text(blackboxes(), newline="\n")
    (out / "info.yaml").write_text(INFO.format(files="\n".join(f'    - "{f}"' for f in files)), newline="\n")
    (out / "src/config.json").write_text(json.dumps(config(period, density), indent=2) + "\n", newline="\n")
    shutil.copy(HERE / "vendor/pdn_cfg.tcl", out / "src/pdn_cfg.tcl")
    for f in ("librelane_plugin_sram_pdn.py", "odb_stripes.py"):
        shutil.copy(HERE / "vendor" / f, out / f)
    (out / "docs/info.md").write_text("## How it works\n\nSee wiki/ARCHITECTURE.md and wiki/SPEC.md in the "
                                      "project repository.\n\n## How to test\n\nLoad a program over the host SPI "
                                      "pins (wiki/TOOLCHAIN.md).\n", newline="\n")
    (out / "test/README.md").write_text("Tests live in code/tests in the project repository.\n", newline="\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--period", type=float, default=16.667)
    ap.add_argument("--density", type=int, default=60)
    ap.add_argument("--tgz")
    a = ap.parse_args()
    out = Path(a.out)
    build(out, a.period, a.density)
    if a.tgz:
        with tarfile.open(a.tgz, "w:gz") as t:
            for p in sorted(out.rglob("*")):
                if p.is_file():
                    b = p.read_bytes().replace(b"\r\n", b"\n")
                    ti = tarfile.TarInfo(p.relative_to(out).as_posix())
                    ti.size, ti.mode = len(b), 0o644
                    import io
                    t.addfile(ti, io.BytesIO(b))
    print(f"project in {out}" + (f", packed to {a.tgz}" if a.tgz else ""))


if __name__ == "__main__":
    main()
