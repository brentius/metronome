"""compile_score: score text -> checked, projected, allocated, assembled image for one role (SPEC A 12)."""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from . import _paths  # noqa: F401
from metronome2_tools.asm import AsmError, assemble_text
from metronome2_tools.check import check as static_check
from metronome2_tools.image import build_image, host_writes
from score import check, check_binding, parse, parse_bind
from score.ast import Score

from . import report as rpt
from .ctx import Ctx
from .emit import Builder
from .flatten import frame_shape, merge_syms
from .plan import (CompileError, driven_wires, explicit_samples, plan_clock, plan_rx, plan_taps, plan_tx,
                   read_wires, validate_taps)


@dataclass
class Compiled:
    score: Score
    role: str
    bind: dict
    mas: str
    program: object = None
    image: dict | None = None
    ctx: Ctx | None = None
    report: str = ""
    check_report: object = None
    errors: list = field(default_factory=list)
    warnings: list = field(default_factory=list)
    host: dict = field(default_factory=dict)

    @property
    def ok(self) -> bool:
        return not self.errors

    def writes(self):
        return host_writes(self.program)


def _load(source) -> Score:
    if isinstance(source, Score):
        return source
    if isinstance(source, Path) or (isinstance(source, str) and "\n" not in source and Path(source).exists()):
        return parse(Path(source).read_text(encoding="utf-8"))
    return parse(source)


def compile_score(source, role: str, bind, *, rate_hz=None, follow_period=None, name=None, assemble=True,
                  raise_on_check=True, skip_periodic=False, params=None, listener=False, tick_beats=None,
                  autobaud=None) -> Compiled:
    """Compile one role of a score.  `bind` maps wire names to pins ('tx=O8', or {'tx': (None, 8)})."""
    score = _load(source)
    if role not in score.roles:
        raise CompileError("E-NAMES", f"unknown role '{role}' (roles: {', '.join(score.roles)})")
    if score.over is not None:
        raise CompileError("E-LAYER", f"'{score.name}' is layered over {score.over[0]}.{score.over[1]}: compile it "
                                      f"with scorec.compile_layered (part A 18.2)")
    es = [d for d in check(score) if d.code.startswith("E-")]
    if es:
        raise CompileError(es[0].code, "; ".join(str(e) for e in es))
    bindd = parse_bind(bind) if isinstance(bind, str) else dict(bind)
    be = check_binding(score, role, bindd)
    if be:
        raise CompileError("E-BIND", "; ".join(str(e) for e in be))
    if len(score.groups) > 1:
        raise CompileError("E-UNSUPPORTED", "scores with several line groups are not compiled yet")
    if score.bits.stuff is not None or score.bits.differential is not None:
        # The templates never implemented these; compiling them would silently emit plain NRZ without stuffed bits.
        what = "stuff" if score.bits.stuff is not None else "differential"
        raise CompileError("E-UNSUPPORTED", f"'bits ..., {what} ...' coding is not compiled (the codec implements it; the "
                                            f"sender and receiver templates would silently ignore it)")
    if any(w.dir == "shared" for w in score.all_wires()):
        # open-drain addressed bus (SPEC A 16.2 shape): its own template, both roles
        from . import bus
        if score.bits.invert or any(f.type.kind == "parity" for p in score.prods for f in _fields(p.body)):
            raise CompileError("E-UNSUPPORTED", "bus template: 'invert' coding and parity fields are not compiled yet")
        clk = plan_clock(score, role, rate_hz, follow_period)
        b = Builder(f"{score.name} / {role}: generated by scorec from {score.name}.score")
        x = Ctx(score, role, [], None, clk, [], None, None, {}, bindd, b, score.bits.order)
        if score.bits.order != "msb":
            raise CompileError("E-UNSUPPORTED", "bus template: fields must be sent most significant bit first")
        x.opts["rate_hz"] = rate_hz
        bus.compile_bus(x, follow_period, params)
        return _finish(score, role, bindd, b, x, assemble, raise_on_check)
    _reject_receive_coding(score, role, rate_hz, follow_period)
    shape = frame_shape(score)
    if shape.periodic and not skip_periodic:
        raise CompileError("E-UNSUPPORTED", f"'every {shape.periodic[0][0].value} {shape.periodic[0][0].unit}: ...' "
                                            f"(periodic transmission, e.g. link pulses) is not compiled yet")
    frame = merge_syms(shape.frame)
    clock = score.clock_for()
    clk = plan_clock(score, role, rate_hz, follow_period)
    driven = driven_wires(score, role)
    rx_pts = explicit_samples(score, clock, role, clk.period) if clk.period else {}
    if clk.mode == "follow" and not rx_pts:
        rx_pts = {}
    taps, slots = ([], {}) if clk.mode == "follow" else plan_taps(score, role, clk, driven, rx_pts)
    txp = plan_tx(score, role, driven, taps) if driven else None
    b = Builder(f"{score.name} / {role}: generated by scorec from {score.name}.score")
    x = Ctx(score, role, frame, shape, clk, taps, txp, None, slots, bindd, b, score.bits.order)
    if autobaud is not None and autobaud is not False:
        if clk.mode != "started":
            raise CompileError("E-UNSUPPORTED", f"autobaud: role {role} is not a 'started by' receiver")
        x.opts["autobaud"] = {"on": True, **(autobaud if isinstance(autobaud, dict) else {})}
    if listener:
        if clk.mode not in ("started", "recovered"):
            raise CompileError("E-UNSUPPORTED", f"listener: role {role} is not a receiving role")
        x.opts["listener"] = True
        x.opts["tick_beats"] = tick_beats
        from . import listener as _l
        _l.add_log_init(x, 3)
    if clk.mode == "generated":
        x.rxp = plan_rx(score, role, taps, slots, bindd, "") if slots else None
        from . import tx
        g = tx.gen_tx(x)
        tx.finish_tx(x, g)
    elif clk.mode in ("started", "recovered"):
        from . import rx
        rx.compile_rx(x)
    elif clk.mode == "follow":
        from . import follower
        follower.compile_follower(x, follow_period)
    else:
        raise CompileError("E-UNSUPPORTED", f"clock mode '{clk.mode}'")
    return _finish(score, role, bindd, b, x, assemble, raise_on_check)


def _fields(n):
    from score.analysis import fields_in
    return fields_in(n)


def _reject_receive_coding(score, role, rate_hz, follow_period):
    """Receivers do not implement `invert` or parity checking yet: refuse rather than compile a wrong program."""
    if plan_clock(score, role, rate_hz, follow_period).mode == "generated":
        return
    if score.bits.invert:
        raise CompileError("E-UNSUPPORTED", f"role {role}: 'invert' coding on a receiving role is not compiled yet")
    for p in score.prods:
        for f in _fields(p.body):
            if f.type.kind == "parity":
                raise CompileError("E-UNSUPPORTED", f"role {role}: checking parity field '{f.name}' is not compiled "
                                                    f"yet (the sender computes it)")


def _finish(score, role, bindd, b, x, assemble, raise_on_check) -> Compiled:
    # Bus templates have their own tap planner. Validate generated phases here
    # too, before a disabled trigger can turn an invalid program into a warning.
    if x.clk.mode == "generated":
        validate_taps(x.clk, x.taps)
    mas = b.text()
    out = Compiled(score, role, bindd, mas, ctx=x, host=x.host)
    if assemble:
        try:
            prog = assemble_text(mas, f"{score.name}.{role}.mas")
        except AsmError as e:
            raise CompileError("E-ASM", f"internal: generated assembly does not assemble: {e}\n{mas}") from None
        out.program = prog
        out.image = build_image(prog)
        rep = static_check(prog)
        out.check_report = rep
        out.errors = [rpt.time_diag(x, prog, rep, e) for e in rep.errors]
        out.warnings = list(rep.warnings) + list(prog.warnings)
        if out.errors and raise_on_check:
            raise CompileError("E-TIME", "\n".join(out.errors))
    out.report = rpt.fit_report(out)
    return out
