"""SPI-style listener (chip-select framed, clocked by one wire, one or two sampled data wires).

Resources (the listener drives nothing: no `.out` block, no transmit stream, so every output-enable table stays 0):

* line 0   follower on the clock wire (boundary = the clock's follow edge, tap 0 = the capture edge), pin A = first data wire.
* line 2   the same on the second data wire (only when the score samples two wires), pin A = second data wire.
* line 1   free-running timestamp ruler (`tick_cycles` chip cycles per tick); pin A = the chip-select wire, whose edges
           trigger the select and deselect threads.
* thread 0 (L0.TAP0)      append the captured bit to receive stream 0 and count it (CNT0, 16-bit down counter).
* thread 1 (L2.TAP0)      append the second data wire's bit to receive stream 1.
* thread 2 (L1 PINA.FALL) chip select asserted: CNT0 := 0xFFFF, start both capture lines.
* thread 3 (L1 PINA.RISE) chip select released: stop the lines, flag a transaction that ended inside a byte (status bit
                          1), append the record to the log (listener.py), flush a partial last byte, post the status.
* thread 4 (L1.BEAT)      the ruler.
* thread 5                one-time init of the counters and the log pointer.

Receive streams are not rewound between transactions: transaction k's payload follows transaction k-1's, each padded to
a whole byte (the flush at deselect), and the record's `bits` tells the host how long each one was.
"""
from __future__ import annotations

from . import listener as L
from .ctx import RX_BASE, Ctx, emit_init_thread, emit_threads
from .emit import Builder, imm
from .flatten import frame_shape, merge_syms
from .plan import CompileError

STREAM_LEN = 0x1F0
F_FRAMING = 1
F_SELECTED = 7           # internal marker, cleared before the record is written


def _sampled_wires(score):
    seen = []
    for sd in score.symbols:
        for w, _ in sd.samples:
            wn = w or (sd.waves[0][0] if sd.waves else None)
            if wn and wn not in seen:
                seen.append(wn)
    return seen


def compile_spi_listener(score, bind, follower, follow_period, tick_cycles, raise_on_check):
    from . import api
    clock = score.clock_for()
    rc = clock.roles[follower]
    clkw = rc.wire
    if not rc.cap_wire:
        raise CompileError("E-UNSUPPORTED", f"listener: role {follower} needs 'capture on WIRE rise|fall'")
    edges = [r for r in score.recognise if r.kind == "edge" and r.edge in ("falls", "rises")]
    fall = [r for r in edges if r.edge == "falls"]
    rise = [r for r in edges if r.edge == "rises"]
    if len(fall) != 1 or len(rise) != 1 or fall[0].wire != rise[0].wire:
        raise CompileError("E-UNSUPPORTED", "listener: needs recognised events 'W falls' and 'W rises' (frame start/end)")
    csw = fall[0].wire
    data = [w for w in _sampled_wires(score) if w not in (clkw, csw)]
    if not 1 <= len(data) <= 2:
        raise CompileError("E-UNSUPPORTED", f"listener: needs one or two sampled data wires, found {data}")
    for w in [clkw, csw] + data:
        if bind.get(w, (None, None))[0] is None:
            raise CompileError("E-BIND", f"wire '{w}' needs an input pin P<k>")
    nominal = float(60e6 / float(clock.rate)) if clock.rate else None
    mod = int(follow_period or (4 * nominal if nominal else 0))
    if not mod:
        raise CompileError("E-RATE", "listener: pass follow_period=<longest clock period in cycles>")
    minper = max(4, int(nominal / 2)) if nominal else 8
    minhalf = max(2, minper // 2)
    tick = int(tick_cycles or (round(nominal) if nominal else 64))
    shape = frame_shape(score)
    clk = api.plan_clock(score, follower, None, follow_period)
    clk.mod = mod
    b = Builder(f"{score.name} / listener: generated by scorec from {score.name}.score")
    x = Ctx(score, "listener", merge_syms(shape.frame), shape, clk, [], None, None, {}, bind, b, score.bits.order)
    x.opts["listener"] = True
    pin = {w: bind[w][0] for w in [clkw, csw] + data}
    ident = 0xAAAAAAAA                      # IN0 = the sampled bit, IN1 = 0
    for ln, w in zip((0, 2), data):
        b.block(f".line {ln}", ["inc 1", f"mod {mod}", "follow", f"edge P{pin[clkw]} {rc.edge}",
                                f"t0edge P{pin[clkw]} {rc.cap_edge}", f"pins A=P{pin[w]}", f"lut0 0x{ident:08X}",
                                "lut1 0x00000000", "snap tap0", f"minperiod {minper}", f"minhalf {minhalf}"])
    b.block(".line 1", ["inc 1", f"mod {tick}", "taps - - -", f"pins A=P{pin[csw]}", "ctl run"])
    streams = {}
    for k, w in enumerate(data):
        start = RX_BASE + k * STREAM_LEN
        b.block(f".stream {k}", ["mode rx", f"order {'msb' if x.msb else 'lsb'}", f"start {start}", f"len {STREAM_LEN}"])
        streams[w] = k
    order = {0: 0, 2: 1}
    c0, c1 = b.cores[0], b.cores[1]
    # thread 0: capture (and count) the first data wire
    c1.label("cap0")
    c1.i(["L.IN -> S0.RX", "ZERO -> CNT0.DEC"], goto="cap0", pause=True, note="bit of the first data wire; count it")
    if len(data) == 2:
        c1.label("cap1")
        c1.i(["L.IN -> S1.RX"], goto="cap1", pause=True, note="bit of the second data wire")
    c1.label("tick")
    c1.i(["ZERO -> CNT1.DEC"], goto="tick", pause=True, note="listener ruler")
    c0.label("cs_on")
    c0.i([imm(255, "CNT0.LO")], note="chip select asserted: bit counter := 0xFFFF")
    c0.i([imm(255, "CNT0.HI")])
    c0.i([imm(F_SELECTED, "FLAGS.SET")], note="marker: a transaction is open (a deselect with none open is the power-up edge)")
    c0.i([imm(5, "L0.CTL")] + ([imm(5, "L2.CTL")] if len(data) == 2 else []), note="start the capture lines")
    c0.i([], goto="cs_on", pause=True)
    c0.label("cs_off")
    c0.i([], goto="cs_idle", jmode="ifnot", jcond=f"F{F_SELECTED}", note="no open transaction: nothing to record")
    c0.i([imm(F_SELECTED, "FLAGS.CLR")])
    c0.i(["ZERO -> L0.CTL"] + (["ZERO -> L2.CTL"] if len(data) == 2 else []), note="chip select released: stop capture")
    c0.i(["CNT0.LO -> ACC.LD"])
    c0.i([imm(7, "ACC.AND")])
    c0.i([imm(7, "ACC.XOR")], note="zero iff a whole number of bytes was captured")
    c0.i(["! " + imm(F_FRAMING, "FLAGS.SET")], when="ACC.Z", note="transaction ended inside a byte")
    srcs = ["FLAGS.LO", "CNT0.LO", "CNT0.HI"]
    L.emit_log_record(lambda moves, **kw: c0.i(moves, **kw), srcs)
    c0.i([imm(2, "S0.CTL")] + ([imm(2, "S1.CTL")] if len(data) == 2 else []), note="flush a partial last byte")
    c0.i(["? FLAGS.LO -> HOST.OUT"], when="HOST.OUTE", note="status to the host mailbox")
    c0.i([imm(F_FRAMING, "FLAGS.CLR")])
    c0.label("cs_idle")
    c0.i([], goto="cs_off", pause=True)
    n = L.add_log_init(x, 5)
    x.init_moves += [imm(255, "CNT1.LO"), imm(255, "CNT1.HI"), imm(255, "CNT0.LO"), imm(255, "CNT0.HI")]
    threads = [(0, 1, 0, "L0.TAP0", "cap0")]
    if len(data) == 2:
        threads.append((1, 1, 2, "L2.TAP0", "cap1"))
    threads += [(2, 0, 1, "PINA.FALL", "cs_on"), (3, 0, 1, "PINA.RISE", "cs_off"), (4, 1, 1, "L1.BEAT", "tick")]
    emit_threads(x, threads)
    emit_init_thread(x, 5, core=1, line=1)
    x.host["listener"] = {"protocol": "spi", "record_bytes": 5, "log_base": 0, "log_records": n, "tick": f"{tick} cycles",
                          "positions": [], "fields": ["status", "bits_lo", "bits_hi", "ts_lo", "ts_hi"],
                          "streams": streams, "stream_base": {w: RX_BASE + k * STREAM_LEN for w, k in streams.items()},
                          "stream_len": STREAM_LEN}
    x.host["mailbox_out"].append("transaction status byte (bit 1: ended inside a byte), 0 = clean")
    x.notes.append(f"listener: follower period up to {mod} cycles, ruler tick {tick} cycles")
    return api._finish(score, "listener", bind, b, x, True, raise_on_check)
