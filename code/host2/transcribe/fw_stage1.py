"""Stage 1 of on-chip UART inference (v4 Phase 0): the bit time of an unknown NRZ wire, as firmware.

The chip captures `NREC` edges of pin `pin` into S0 (SPEC v2 12.4, started by a CW write of EMASK/ECTL), then runs the
algorithm of `chipinfer.stage1` step for step and writes the learned beat to line 0 (INC = 32, MOD = TU, by CW) and a
result block to data RAM. No host action after the image load.

`framing` quantises captured runs into logical bits and tests UART widths 5–9
with none/even/odd parity. It takes the first shortest candidate with at least
four complete valid frames and measures the minimum stop interval between frames.
Every interior run must quantise to 1–15 bits. With `transmit`, line 0 and S1
send the quantised bits through the last validated stop bit on O8 at the learned
rate. With `reply`, the transmitter instead frames a byte set at image build
time using the learned format and polarity. Transmission needs at least
16 clocks per bit. `replay_capture` uses S0's raw
edge timing as an alternative to quantisation and framing.

All values are in 1/32 cycle: a record's bytes 1..3 with byte 1 masked to bits 7:5 are DC << 5 (`R`), so no shifts are
needed to read a run. Limits: bit time < 2048 cycles (TU fits 16 bits; >= 29.3 kbaud at 60 MHz) and >= 4 cycles.

Machine techniques (cycle model with the v4 additions, SPEC v2 13):
* **Subroutine as a thread.** There is no call/return. A 32/16 restoring division runs as a server thread on core 1
  (trigger ALWAYS, polls F3); the caller sets F3 and polls until the server clears it. N in LF0, D in CNT1, quotient
  to CNT2.
* **Carry in a flag.** Multi-byte add/subtract: carry or borrow in F1; a carry-in step that does not execute leaves
  the previous C, which is 0 exactly when F1 was 0, so the next guarded step is still right (4 instructions a byte).
* **LFSR at polynomial 0 = right shifter and 32-bit storage.** LF0 accumulates sums; LF1 holds the minimum, the
  cluster limit, the tolerance threshold and the used count.
* **Burst rule kept.** Every wait pauses (both threads are triggered ALWAYS, so they are re-dispatched).

Register map (main, core 0): R0..R2 run value / remainder, R3 k or count, CNT0 run counter, CNT1 sum of k (divisor),
CNT2 TU, LF0 sum of R (dividend), LF1 B0..B2 min/limit or B0/B1 threshold + B2 used + B3 run byte 2, SH0/SH1 run
bytes 0/1 (quantise) or the division shift register (server), F1 carry, F2 division bit 16, F3 call, F4 cluster
mode, F5 quantise mode.
Result block at RES (0x710): status (1 ok, 2 bit time too long, 3 no consistent bit time), idle, TU lo, TU hi, used,
mult. Framing appends its result at FRAME_RES. HOST.OUT reports completion:
the stage 1 status if bit-time inference failed, otherwise the framing status,
4 if framing passed and the bit time was too short for transmission, or 5
if the reply does not fit the learned data width.
"""
from __future__ import annotations

RES = 0x710
VARS = 0x700            # TU0 lo/hi, mult, pass counter
DBG = 0x2460
FRAME_RES = RES + 6     # status (1 found, 2 quantisation failed, 3 no match), width, parity, frames, minimum stop bits
PACKED_BITS = 0x400
S1_CONFIG = 0x20D8


def source(pin: int = 5, nrec: int = 64, *, replay_capture: bool = False, framing: bool = False,
           transmit: bool = False, reply: int | None = None) -> str:
    if not 0 <= pin < 13:
        raise ValueError("capture pin must be P0 through P12")
    if framing and (replay_capture or not 8 <= nrec <= 64):
        raise ValueError("framing requires 8–64 records and exclusive use of the capture")
    if transmit and not framing:
        raise ValueError("transmission requires a framing check")
    if reply is not None and (not transmit or not isinstance(reply, int) or not 0 <= reply <= 255):
        raise ValueError("reply requires transmission and a byte value")
    runs = nrec - 1
    need = -(-9 * runs // 10)                      # used * 10 >= 9 * runs
    L = []

    def i(s=""):
        L.append("        " + (s if s else "nop"))

    def lab(n):
        L.append(f"{n}:")

    def wait_rdy(n):
        lab(n)
        i(f"pause goto {n} ifnot P0.RDY")

    def p0_at(addr):
        i(f"#{addr & 0xFF} -> P0.AL")
        i(f"#{addr >> 8} -> P0.AH")

    def call_div(tag):
        i("#3 -> FLAGS.SET")
        lab(f"dw_{tag}")
        i(f"pause goto dw_{tag} if F3")

    hdr = [f"; stage 1 UART inference firmware (generated by fw_stage1.py): pin P{pin}, {nrec} records", ".clock 60e6",
           ".stream 0", "    mode rx", "    start 0", f"    len {4 * nrec}", ".end",
           ".thread 0", "    core 0", "    trigger ALWAYS", "    start main", ".end",
           ".thread 1", "    core 1", "    trigger ALWAYS", "    start srv", ".end",
           ".thread 2", "    core 1", "    trigger ALWAYS", "    start qsrv", ".end", "", ".core 0"]
    if framing:
        hdr[2:2] = [".stream 1", "    mode rx", f"    start {PACKED_BITS}", "    len 120", ".end"]
    if transmit:
        hdr[2:2] = [".out 8", "    line 0", "    sel 0 0 0", "    lut b0", ".end",
                    ".thread 3", "    core 1", "    trigger L0.BEAT", "    start tx_sample", ".end"]
    # ---------------------------------------------------------------- init: start the capture by CW, wait for it
    lab("main")
    em = DBG + 0x08
    i(f"#{em & 0xFF} -> CW.AL")
    i(f"#{em >> 8} -> CW.AH")
    i(f"#{(1 << pin) & 0xFF} -> CW.D" if (1 << pin) & 0xFF else "ZERO -> CW.D")
    i()
    i(f"#{(1 << pin) >> 8} -> CW.D" if (1 << pin) >> 8 else "ZERO -> CW.D")
    i(f"#{(DBG + 2) & 0xFF} -> CW.AL")
    i("#1 -> CW.D")
    lab("wcap")
    i("pause goto wcap ifnot S0.END")
    # ---------------------------------------------------------------- pass 0: minimum run (LF1 = 0xFFFFFF)
    i("#255 -> LF1.B0")
    i("#255 -> LF1.B1")
    i("#255 -> LF1.B2")
    lab("pset")                                       # every pass starts here: P0 at record 1 byte 1, CNT0 = runs
    p0_at(5)
    i(f"#{runs} -> CNT0.LO")
    i("ZERO -> CNT0.HI")
    # ---------------------------------------------------------------- run reader (shared by every pass)
    wait_rdy("rd")
    i("P0.D -> ACC.LD, ZERO -> P0.R")
    i("#224 -> ACC.AND")
    i("ACC -> R0")
    wait_rdy("rd1")
    i("P0.D -> R1, ZERO -> P0.R")
    wait_rdy("rd2")
    i("P0.D -> R2, ZERO -> P0.R")
    wait_rdy("rd3")
    i("ZERO -> P0.R, goto qm if F5")                 # skip byte 0 of the next record; dispatch on the mode
    i("goto cm if F4")
    # ---------------------------------------------------------------- min mode: R < LF1 ?
    i("R2 -> ACC.LD")
    i("LF1.B2 -> ACC.CMP")
    i("goto mupd ifnot ACC.C")
    i("R1 -> ACC.LD, goto next ifnot ACC.Z")
    i("LF1.B1 -> ACC.CMP")
    i("goto mupd ifnot ACC.C")
    i("R0 -> ACC.LD, goto next ifnot ACC.Z")
    i("LF1.B0 -> ACC.CMP")
    i("goto next if ACC.C")
    lab("mupd")
    i("R0 -> LF1.B0")
    i("R1 -> LF1.B1")
    i("R2 -> LF1.B2")
    # ---------------------------------------------------------------- loop end (shared)
    lab("next")
    i("ZERO -> CNT0.DEC")
    i("goto rd ifnot CNT0.Z")
    i("goto aq if F5")
    i("goto ac if F4")
    # ---------------------------------------------------------------- after min: m < 65536, lim = m + m/2
    i("LF1.B2 -> ACC.LD")
    i("goto flong ifnot ACC.Z")
    i("LF1.B0 -> R0")
    i("LF1.B1 -> R1, ZERO -> R2")
    i("ZERO -> LF1.B3")
    i("ZERO -> LF1.ST")
    for k, src in ((0, "R0"), (1, "R1"), (2, "R2")):
        i(f"LF1.B{k} -> ACC.LD")
        if k:
            i("when F1 ? #1 -> ACC.ADD, #1 -> FLAGS.CLR")
        i(f"when ACC.C {src} -> ACC.ADD" + (", ? #1 -> FLAGS.SET" if k else ""))
        i(f"when ACC.C ACC -> LF1.B{k}, ? #1 -> FLAGS.SET")
    i("#1 -> FLAGS.CLR")
    i("ZERO -> LF0.B0, ZERO -> R3")                   # cluster: LF0 = sum, R3 = count
    i("ZERO -> LF0.B1")
    i("ZERO -> LF0.B2")
    i("ZERO -> LF0.B3")
    i("#4 -> FLAGS.SET")
    i("goto pset")
    # ---------------------------------------------------------------- cluster mode: R <= lim -> sum, count
    lab("cm")
    i("R2 -> ACC.LD")
    i("LF1.B2 -> ACC.CMP")
    i("goto cadd ifnot ACC.C")
    i("R1 -> ACC.LD, goto next ifnot ACC.Z")
    i("LF1.B1 -> ACC.CMP")
    i("goto cadd ifnot ACC.C")
    i("R0 -> ACC.LD, goto next ifnot ACC.Z")
    i("LF1.B0 -> ACC.CMP")
    i("goto cadd ifnot ACC.C")
    i("goto next ifnot ACC.Z")
    lab("cadd")
    i("LF0.B0 -> ACC.LD")
    i("R0 -> ACC.ADD")
    i("when ACC.C ACC -> LF0.B0, LF0.B1 -> ACC.LD, ? #1 -> FLAGS.SET")
    i("when F1 ? #1 -> ACC.ADD, #1 -> FLAGS.CLR")
    i("when ACC.C R1 -> ACC.ADD, ? #1 -> FLAGS.SET")
    i("when ACC.C ACC -> LF0.B1, LF0.B2 -> ACC.LD, ? #1 -> FLAGS.SET")
    i("when F1 ? #1 -> ACC.ADD, #1 -> FLAGS.CLR")
    i("when ACC.C R2 -> ACC.ADD, ? #1 -> FLAGS.SET")
    i("when ACC.C ACC -> LF0.B2, LF0.B3 -> ACC.LD, ? #1 -> FLAGS.SET")
    i("when F1 ? #1 -> ACC.ADD, #1 -> FLAGS.CLR")
    i("ACC -> LF0.B3, R3 -> ACC.LD")
    i("#1 -> ACC.ADD")
    i("ACC -> R3, goto next")
    # ---------------------------------------------------------------- after cluster: TU0 = sum / count
    lab("ac")
    i("#4 -> FLAGS.CLR")
    i("R3 -> CNT1.LO")
    i("ZERO -> CNT1.HI")
    i("LF0.B3 -> ACC.LD")
    i("goto flong ifnot ACC.Z")
    i("LF0.B2 -> ACC.LD")
    i("R3 -> ACC.CMP")
    i("goto flong if ACC.C")
    call_div("c")
    p0_at(VARS)                                       # store TU0 and mult = 1
    i("CNT2.LO -> P0.W")
    i("CNT2.HI -> P0.W")
    i("#1 -> P0.W")
    # ---------------------------------------------------------------- candidate: TU = TU0 / mult
    lab("cand")
    i("ZERO -> LF0.B2")
    i("ZERO -> LF0.B3")
    p0_at(VARS)
    wait_rdy("cr0")
    i("P0.D -> LF0.B0, ZERO -> P0.R")
    wait_rdy("cr1")
    i("P0.D -> LF0.B1, ZERO -> P0.R")
    wait_rdy("cr2")
    i("P0.D -> CNT1.LO, ZERO -> P0.R")
    i("ZERO -> CNT1.HI")
    call_div("m")
    i("CNT2.HI -> ACC.LD")                            # TU >= 128 ?
    i("goto tuok ifnot ACC.Z")
    i("CNT2.LO -> ACC.LD")
    i("#128 -> ACC.CMP")
    i("goto cfail ifnot ACC.C")
    lab("tuok")
    p0_at(VARS + 3)
    i("#3 -> P0.W")                                   # 3 refinement passes
    # ---------------------------------------------------------------- pass: thr = TU/4 + TU/16 + TU/32
    lab("pass")
    i("CNT2.LO -> LF1.B0")
    i("CNT2.HI -> LF1.B1")
    i("ZERO -> LF1.B2")
    i("ZERO -> LF1.B3")
    i("ZERO -> LF1.ST")
    i("ZERO -> LF1.ST")
    i("LF1.B0 -> R0")
    i("LF1.B1 -> R1, ZERO -> LF1.ST")
    i("ZERO -> LF1.ST")
    for step in (0, 1):                               # += TU/16, then (after one more shift) += TU/32
        i("LF1.B0 -> ACC.LD")
        i("R0 -> ACC.ADD")
        i("when ACC.C ACC -> R0, LF1.B1 -> ACC.LD, ? #1 -> FLAGS.SET")
        i("when F1 ? #1 -> ACC.ADD, #1 -> FLAGS.CLR")
        i("R1 -> ACC.ADD" + (", ZERO -> LF1.ST" if step == 0 else ""))
        i("ACC -> R1")
    i("R0 -> LF1.B0")
    i("R1 -> LF1.B1")
    i("ZERO -> LF1.B2")                               # used = 0
    i("ZERO -> LF0.B0, ZERO -> CNT1.LO")
    i("ZERO -> LF0.B1, ZERO -> CNT1.HI")
    i("ZERO -> LF0.B2")
    i("ZERO -> LF0.B3")
    i("#5 -> FLAGS.SET")
    i("goto pset")
    lab("qm")                                         # quantise this run on core 1 (server thread 2, F6)
    i("#6 -> FLAGS.SET")
    lab("qw")
    i("pause goto qw if F6")
    i("goto next")
    # ---------------------------------------------------------------- after a pass: TU = sum R / sum k
    lab("aq")
    if framing:
        i("goto framing_ready if F7")
    i("CNT1.HI -> ACC.LD")                            # sum k = 0 ?
    i("goto aq1 ifnot ACC.Z")
    i("CNT1.LO -> ACC.LD")
    i("goto cfail if ACC.Z")
    lab("aq1")                                        # (sum R >> 16) >= sum k -> overflow
    i("LF0.B3 -> ACC.LD")
    i("CNT1.HI -> ACC.CMP")
    i("goto aq2 ifnot ACC.C")
    i("LF0.B2 -> ACC.LD, goto cfail ifnot ACC.Z")
    i("CNT1.LO -> ACC.CMP")
    i("goto cfail if ACC.C")
    lab("aq2")
    call_div("q")
    p0_at(VARS + 3)                                   # passes left
    wait_rdy("pr")
    i("P0.D -> ACC.LD")
    i("#1 -> ACC.SUB")
    i(f"#{(VARS + 3) & 0xFF} -> P0.AL")
    i("ACC -> P0.W, goto pass ifnot ACC.Z")
    i("#5 -> FLAGS.CLR")
    i("LF1.B2 -> ACC.LD")                             # used >= 90 % of runs and TU >= 128
    i(f"#{need} -> ACC.CMP")
    i("goto cfail ifnot ACC.C")
    i("CNT2.HI -> ACC.LD")
    i("goto ok ifnot ACC.Z")
    i("CNT2.LO -> ACC.LD")
    i("#128 -> ACC.CMP")
    i("goto ok if ACC.C")
    lab("cfail")                                      # next candidate: mult + 1 (up to 3)
    i("#5 -> FLAGS.CLR")
    p0_at(VARS + 2)
    wait_rdy("mr")
    i("P0.D -> ACC.LD")
    i("#1 -> ACC.ADD")
    i(f"#{(VARS + 2) & 0xFF} -> P0.AL")
    i("ACC -> P0.W")
    i("#4 -> ACC.CMP")
    i("goto cand ifnot ACC.Z")
    i("#3 -> R3")
    i("goto out")
    lab("flong")
    i("#2 -> R3")
    i("goto out")
    lab("ok")
    i(f"#{0x2000 & 0xFF} -> CW.AL")          # learned beat on line 0: INC = 32, MOD = TU
    i(f"#{0x2000 >> 8} -> CW.AH")
    i("#32 -> CW.D")
    i()
    i("ZERO -> CW.D")
    i()
    i("CNT2.LO -> CW.D")
    i("#1 -> R3")
    i("CNT2.HI -> CW.D")
    # ---------------------------------------------------------------- result block: status, idle, TU, used, mult
    lab("out")
    p0_at(pin // 8)
    wait_rdy("ir")
    i(f"P0.D -> ACC.LD")
    i(f"#{1 << (pin % 8)} -> ACC.AND")
    if replay_capture:
        # ACC.Z is set when the first edge lands low, so the idle level is high.
        rlv = DBG + 0x12 + pin // 8
        i(f"#{rlv & 0xFF} -> CW.AL")
        i(f"#{rlv >> 8} -> CW.AH")
        i(f"when ACC.Z ? #{1 << (pin % 8)} -> R1, ! ZERO -> R1")
        i("R1 -> CW.D")
    p0_at(RES)
    i("R3 -> P0.W" + ("" if framing else ", R3 -> HOST.OUT") + ", goto idl0 ifnot ACC.Z")
    i("#1 -> P0.W")
    i("goto res2")
    lab("idl0")
    i("ZERO -> P0.W")
    lab("res2")
    i("CNT2.LO -> P0.W")
    i("CNT2.HI -> P0.W")
    i("LF1.B2 -> P0.W")
    i(f"#{(VARS + 2) & 0xFF} -> P0.AL")
    i(f"#{(VARS + 2) >> 8} -> P0.AH")
    wait_rdy("ow2")
    i("P0.D -> R0")
    i(f"#{(RES + 5) & 0xFF} -> P0.AL")
    i(f"#{(RES + 5) >> 8} -> P0.AH")
    i("R0 -> P0.W")
    if framing:
        i("R3 -> ACC.LD")
        i("#1 -> ACC.CMP")
        i("goto framing_start if ACC.Z")
        i("R3 -> HOST.OUT")
    if replay_capture:
        i("R3 -> ACC.LD")
        i("#1 -> ACC.CMP")
        i("goto finished ifnot ACC.Z")
        i(f"#{(DBG + 2) & 0xFF} -> CW.AL")
        i("#2 -> CW.D")
        i("#1 -> S0.CTL")
        lab("finished")
    i("ZERO -> T.STOP   pause goto main")
    if framing:
        lab("framing_start")
        i("#2 -> FLAGS.CLR")
        i("#7 -> FLAGS.SET")
        i("goto pass")  # Reuse the final learned TU and recompute its tolerance window.
        lab("framing_ready")
        i("#2 -> S1.CTL")  # Publish the partial last byte before releasing P0 to core 1.
        i("#5 -> FLAGS.CLR")
        i("#2 -> FLAGS.SET")
        i("ZERO -> T.STOP   pause goto main")
    # ================================================================ core 1: 32/16 division server
    L.append("")
    L.append(".core 1")
    lab("srv")
    i("goto dv if F3")
    i("pause goto srv")
    lab("dv")
    i("LF0.B2 -> R0, #16 -> SH0.CFG")
    i("LF0.B3 -> R1, #16 -> SH1.CFG")
    i("#2 -> FLAGS.CLR")
    i("LF0.B0 -> SH0.LD, LF0.B1 -> SH1.LD")
    i("#16 -> CNT0.LO")
    i("ZERO -> CNT0.HI, #1 -> FLAGS.CLR")
    lab("dl")                                         # rem = rem * 2 + next dividend bit
    i("R0 -> ACC.LD")
    i("R0 -> ACC.ADD")
    i("when ACC.C SH1.O -> ACC.OR, ? #1 -> FLAGS.SET")
    i("ACC -> R0, R1 -> ACC.LD")
    i("R1 -> ACC.ADD")
    i("when F1 ? #1 -> ACC.OR, #1 -> FLAGS.CLR")
    i("when ACC.C ACC -> R1, ? #2 -> FLAGS.SET")
    i("R1 -> ACC.LD, goto dsub if F2")               # rem >= D ?
    i("CNT1.HI -> ACC.CMP")
    i("goto dno ifnot ACC.C")
    i("R0 -> ACC.LD, goto dsub ifnot ACC.Z")
    i("CNT1.LO -> ACC.CMP")
    i("goto dno ifnot ACC.C")
    lab("dsub")
    i("R0 -> ACC.LD")
    i("CNT1.LO -> ACC.SUB")
    i("when ACC.C ACC -> R0, R1 -> ACC.LD, ! #1 -> FLAGS.SET")
    i("CNT1.HI -> ACC.SUB")
    i("when F1 ? #1 -> ACC.SUB, #1 -> FLAGS.CLR")
    i("ACC -> R1, #2 -> FLAGS.CLR")
    i("SH0.O -> SH1.SH, #1 -> SH0.SH, ZERO -> CNT0.DEC")
    i("pause goto dl ifnot CNT0.Z")
    i("goto dend")
    lab("dno")
    i("SH0.O -> SH1.SH, ZERO -> SH0.SH, ZERO -> CNT0.DEC")
    i("pause goto dl ifnot CNT0.Z")
    lab("dend")
    i("SH0.D -> CNT2.LO")
    i("SH1.D -> CNT2.HI")
    i("#3 -> FLAGS.CLR")
    i("pause goto srv")
    # ================================================================ core 1: quantise server (thread 2, F6)
    lab("qsrv")
    i("goto qsv if F6")
    if framing:
        i("goto qframe if F7")
    i("pause goto qsrv")
    lab("qsv")
    i("R0 -> SH0.LD, R1 -> SH1.LD, R2 -> LF1.B3")    # keep R for the sum
    i("ZERO -> R3")
    lab("qs")                                         # while x >= TU: x -= TU, k++ (k > 15 rejects)
    i("R2 -> ACC.LD")
    i("goto qge ifnot ACC.Z")
    i("R1 -> ACC.LD")
    i("CNT2.HI -> ACC.CMP")
    i("goto qdone ifnot ACC.C")
    i("R0 -> ACC.LD, goto qge ifnot ACC.Z")
    i("CNT2.LO -> ACC.CMP")
    i("goto qdone ifnot ACC.C")
    lab("qge")
    i("R3 -> ACC.LD")
    i("#15 -> ACC.CMP")
    i("goto qret if ACC.Z")
    i("#1 -> ACC.ADD")
    i("ACC -> R3, R0 -> ACC.LD")
    i("CNT2.LO -> ACC.SUB")
    i("when ACC.C ACC -> R0, R1 -> ACC.LD, ! #1 -> FLAGS.SET")
    i("when F1 ? #1 -> ACC.SUB, #1 -> FLAGS.CLR")
    i("when ACC.C CNT2.HI -> ACC.SUB, ! #1 -> FLAGS.SET")
    i("when ACC.C ACC -> R1, R2 -> ACC.LD, ! #1 -> FLAGS.SET")
    i("when F1 ? #1 -> ACC.SUB, #1 -> FLAGS.CLR")
    i("ACC -> R2   pause goto qs")
    lab("qdone")                                      # rem = R1:R0 < TU
    i("R1 -> ACC.LD")
    i("LF1.B1 -> ACC.CMP")
    i("goto kchk ifnot ACC.C")
    i("R0 -> ACC.LD, goto thigh ifnot ACC.Z")
    i("LF1.B0 -> ACC.CMP")
    i("goto kchk ifnot ACC.C")
    lab("thigh")                                      # d = TU - rem < thr ?  then k + 1
    i("CNT2.LO -> ACC.LD")
    i("R0 -> ACC.SUB")
    i("when ACC.C ACC -> R0, CNT2.HI -> ACC.LD, ! #1 -> FLAGS.SET")
    i("R1 -> ACC.SUB")
    i("when F1 ? #1 -> ACC.SUB, #1 -> FLAGS.CLR")
    i("ACC -> R1")
    i("LF1.B1 -> ACC.CMP")
    i("goto hinc ifnot ACC.C")
    i("R0 -> ACC.LD, goto qret ifnot ACC.Z")
    i("LF1.B0 -> ACC.CMP")
    i("goto qret if ACC.C")
    lab("hinc")
    i("R3 -> ACC.LD")
    i("#1 -> ACC.ADD")
    i("ACC -> R3")
    lab("kchk")                                       # 1 <= k <= 15
    i("R3 -> ACC.LD")
    i("goto qret if ACC.Z")
    i("#16 -> ACC.CMP")
    i("goto qret if ACC.C")
    if framing:
        i("goto qpack if F7")
    i("LF0.B0 -> ACC.LD")                             # accept: LF0 += R, CNT1 += k, used++
    i("SH0.D -> ACC.ADD")
    i("when ACC.C ACC -> LF0.B0, LF0.B1 -> ACC.LD, ? #1 -> FLAGS.SET")
    i("when F1 ? #1 -> ACC.ADD, #1 -> FLAGS.CLR")
    i("when ACC.C SH1.D -> ACC.ADD, ? #1 -> FLAGS.SET")
    i("when ACC.C ACC -> LF0.B1, LF0.B2 -> ACC.LD, ? #1 -> FLAGS.SET")
    i("when F1 ? #1 -> ACC.ADD, #1 -> FLAGS.CLR")
    i("when ACC.C LF1.B3 -> ACC.ADD, ? #1 -> FLAGS.SET")
    i("when ACC.C ACC -> LF0.B2, LF0.B3 -> ACC.LD, ? #1 -> FLAGS.SET")
    i("when F1 ? #1 -> ACC.ADD, #1 -> FLAGS.CLR")
    i("ACC -> LF0.B3, CNT1.LO -> ACC.LD")
    i("R3 -> ACC.ADD")
    i("when ACC.C ACC -> CNT1.LO, CNT1.HI -> ACC.LD, ? #1 -> FLAGS.SET")
    i("when F1 ? #1 -> ACC.ADD, #1 -> FLAGS.CLR")
    i("ACC -> CNT1.HI, LF1.B2 -> ACC.LD")
    i("#1 -> ACC.ADD")
    i("ACC -> LF1.B2, goto qret")
    lab("qret")
    if framing:
        i("when F7 ? #0 -> FLAGS.SET")  # Mark the packed stream invalid if a run cannot be quantised.
        lab("qdone_exit")
    i("#6 -> FLAGS.CLR")
    i("pause goto qsrv")
    if framing:
        _append_framing(i, lab, p0_at, wait_rdy, transmit, reply)
    return "\n".join(hdr + L) + "\n"


def _append_framing(i, lab, p0_at, wait_rdy, transmit, reply):
    """Pack bit runs into S1, then test framing candidates on core 1.

    F4 alternates the logical run level, starting with the active level (0).
    LF0.B1:B0 counts valid packed bits so padding is excluded from the scan.
    F0 marks an invalid run. During scanning F1 marks an open frame, CNT0 is
    the remaining sample count, CNT1 is the payload/parity count, and LF1.B2
    accumulates parity. R1 holds the tested width and R0 holds the parity mode.
    """
    lab("qpack")
    i("LF0.B0 -> ACC.LD")
    i("R3 -> ACC.ADD")
    i("when ACC.C ACC -> LF0.B0, LF0.B1 -> ACC.LD, ? #1 -> FLAGS.SET")
    i("when F1 ? #1 -> ACC.ADD, #1 -> FLAGS.CLR")
    i("ACC -> LF0.B1")
    i("ZERO -> R0")
    i("when F4 ? #1 -> R0")
    lab("qbit")
    i("R3 -> ACC.LD, R0 -> S1.RX")
    i("#1 -> ACC.SUB")
    i("ACC -> R3   pause goto qbit ifnot ACC.Z")
    i("when F4 ? #4 -> FLAGS.CLR, ! #4 -> FLAGS.SET")
    i("goto qdone_exit")
    lab("qframe")
    i("pause goto qsrv ifnot F2")
    i("#2 -> R2")
    i("goto fs_report if F0")
    i("#5 -> R1")
    i("ZERO -> R0")
    i("ZERO -> SH0.CFG")
    lab("fs_candidate")
    p0_at(PACKED_BITS)
    i("LF0.B0 -> CNT0.LO")
    i("LF0.B1 -> CNT0.HI")
    i("ZERO -> CNT1.HI, #1 -> FLAGS.CLR")
    i("ZERO -> LF1.B0")
    i("#255 -> LF1.B1")
    i("ZERO -> LF1.B3")
    lab("fs_byte")
    wait_rdy("fs_read")
    i("P0.D -> SH0.LD, ZERO -> P0.R")
    lab("fs_bit")
    i("goto fs_end if CNT0.Z")
    i("goto fs_byte if SH0.DONE")
    i("goto fs_frame if F1")
    i("SH0.O -> ACC.LD")
    i("goto fs_idle ifnot ACC.Z")
    i("LF1.B0 -> ACC.LD")
    i("goto fs_start if ACC.Z")
    i("LF1.B1 -> ACC.CMP")
    i("when ACC.C ! ACC -> LF1.B1")
    lab("fs_start")
    i("R1 -> CNT1.LO, #1 -> FLAGS.SET")
    i("R0 -> ACC.LD")
    i("goto fs_shift if ACC.Z")
    i("#1 -> ACC.AND")
    i("#1 -> ACC.XOR")
    i("ACC -> LF1.B2, R1 -> ACC.LD")
    i("#1 -> ACC.ADD")
    i("ACC -> CNT1.LO, goto fs_shift")
    lab("fs_frame")
    i("goto fs_stop if CNT1.Z")
    i("LF1.B2 -> ACC.LD")
    i("when SH0.OUT ? #1 -> ACC.XOR")
    i("ACC -> LF1.B2, ZERO -> CNT1.DEC, goto fs_shift")
    lab("fs_stop")
    i("SH0.O -> ACC.LD")
    i("goto fs_next if ACC.Z")
    i("R0 -> ACC.LD")
    i("goto fs_good if ACC.Z")
    i("LF1.B2 -> ACC.LD")
    i("goto fs_next ifnot ACC.Z")
    lab("fs_good")
    if transmit and reply is None:
        # The transmitter stops one bit beyond the last validated stop sample.
        i("CNT0.LO -> CNT2.LO")
        i("CNT0.HI -> CNT2.HI")
        i("ZERO -> CNT2.DEC")
    i("LF1.B3 -> ACC.LD, #1 -> FLAGS.CLR")
    i("#1 -> ACC.ADD")
    i("ACC -> LF1.B3")
    i("#1 -> LF1.B0")
    i("goto fs_shift")
    lab("fs_idle")
    i("LF1.B0 -> ACC.LD")
    i("goto fs_shift if ACC.Z")
    i("#1 -> ACC.ADD")
    i("ACC -> LF1.B0")
    lab("fs_shift")
    i("ZERO -> SH0.SH, ZERO -> CNT0.DEC   pause goto fs_bit")
    lab("fs_end")
    i("LF1.B3 -> ACC.LD")
    i("#4 -> ACC.CMP")
    i("#1 -> R2")
    i("goto fs_report if ACC.C")
    lab("fs_next")
    i("R0 -> ACC.LD")
    i("#1 -> ACC.ADD")
    i("ACC -> R0")
    i("#3 -> ACC.CMP")
    i("goto fs_candidate ifnot ACC.Z")
    i("ZERO -> R0, R1 -> ACC.LD")
    i("#1 -> ACC.ADD")
    i("ACC -> R1")
    i("#10 -> ACC.CMP")
    i("goto fs_candidate ifnot ACC.Z")
    i("#3 -> R2")
    lab("fs_report")
    p0_at(FRAME_RES)
    i("R2 -> P0.W")
    i("R2 -> ACC.LD")
    i("#1 -> ACC.CMP")
    i("goto fs_stop_thread ifnot ACC.Z")
    i("R1 -> P0.W")
    i("R0 -> P0.W")
    i("LF1.B3 -> P0.W")
    i("LF1.B1 -> P0.W")
    if transmit:
        i("goto tx_prepare")
    lab("fs_stop_thread")
    i("R2 -> HOST.OUT, ZERO -> T.STOP   pause goto qsrv")

    if transmit:
        lab("tx_prepare")
        p0_at(RES + 3)
        wait_rdy("tx_rate")
        i("P0.D -> ACC.LD")
        i("#2 -> ACC.CMP")  # At least 16 clocks per bit for the transmit thread.
        i("goto tx_fast ifnot ACC.C")
        i(f"#{(RES + 1) & 0xff} -> P0.AL")
        wait_rdy("tx_idle")
        i("P0.D -> ACC.LD")
        i("ZERO -> L.DBIT, #4 -> FLAGS.CLR")
        i("when ACC.Z ! #1 -> L.DBIT")
        i("when ACC.Z ! #4 -> FLAGS.SET")
        if reply is not None:
            _append_reply(i, lab, reply)
            return
        i(f"#{S1_CONFIG & 0xff} -> CW.AL")
        i(f"#{S1_CONFIG >> 8} -> CW.AH")
        i("ZERO -> CW.D")
        i("LF0.B0 -> CNT0.LO")
        i("LF0.B1 -> CNT0.HI")
        i("#1 -> S1.CTL")
        i("#1 -> L0.CTL")
        i("ZERO -> T.STOP   pause goto qsrv")
        lab("tx_fast")
        i("#4 -> R2")
        i("goto fs_stop_thread")
        lab("tx_sample")
        i("CNT0.LO -> ACC.LD")
        i("CNT2.LO -> ACC.CMP")
        i("goto tx_send ifnot ACC.Z")
        i("CNT0.HI -> ACC.LD")
        i("CNT2.HI -> ACC.CMP")
        i("goto tx_done if ACC.Z")
        lab("tx_send")
        i("S1.BIT -> ACC.LD")
        i("when F4 ! #1 -> ACC.XOR")
        i("ACC -> L.DBIT, ZERO -> S1.ADV, ZERO -> CNT0.DEC   pause goto tx_sample")
        lab("tx_done")
        i("R2 -> HOST.OUT, ZERO -> L0.CTL, ZERO -> T.STOP   pause goto tx_sample")


def _append_reply(i, lab, reply):
    """Emit one new frame using R1 (width), R0 (parity), F4 (idle) and LF1.B1 (stop interval)."""
    i("R1 -> ACC.LD")
    i(f"#{reply.bit_length()} -> ACC.CMP")
    i("goto tx_too_wide ifnot ACC.C")
    # Count data separately from the shifter so a 9-bit frame gets a zero ninth bit.
    i("ZERO -> SH0.CFG, R1 -> CNT1.LO, R0 -> ACC.LD")
    i(f"#{reply} -> SH0.LD, ZERO -> CNT1.HI, ZERO -> CNT0.HI")
    i("#1 -> ACC.AND, LF1.B1 -> CNT0.LO")
    i("#1 -> ACC.XOR")
    i("ACC -> LF1.B2")
    i("#1 -> L0.CTL")
    i("ZERO -> T.STOP   pause goto qsrv")
    lab("tx_fast")
    i("#4 -> R2")
    i("goto fs_stop_thread")
    lab("tx_too_wide")
    i("#5 -> R2")
    i("goto fs_stop_thread")

    lab("tx_sample")
    i("when F4 ! #1 -> L.DBIT, ? ZERO -> L.DBIT")
    i("pause goto tx_data")
    lab("tx_data")
    i("LF1.B2 -> ACC.LD, goto tx_end_data if CNT1.Z")
    i("when SH0.OUT ? #1 -> ACC.XOR")
    i("ACC -> LF1.B2, SH0.O -> R3, ZERO -> SH0.SH")
    i("R3 -> ACC.LD")
    i("when F4 ! #1 -> ACC.XOR")
    i("ACC -> L.DBIT, ZERO -> CNT1.DEC   pause goto tx_data")
    lab("tx_end_data")
    i("R0 -> ACC.LD")
    i("goto tx_stop if ACC.Z")
    i("LF1.B2 -> ACC.LD")
    i("when F4 ! #1 -> ACC.XOR")
    i("ACC -> L.DBIT   pause goto tx_stop")
    lab("tx_stop")
    i("when F4 ! ZERO -> L.DBIT, ? #1 -> L.DBIT")
    i("pause goto tx_hold_stop")
    lab("tx_hold_stop")
    i("goto tx_done if CNT0.Z")
    i("ZERO -> CNT0.DEC   pause goto tx_hold_stop")
    lab("tx_done")
    i("R2 -> HOST.OUT, ZERO -> L0.CTL, ZERO -> T.STOP   pause goto tx_sample")


def count_insns(text: str) -> dict:
    out, core = {}, None
    for ln in text.splitlines():
        s = ln.split(";")[0].rstrip()
        if s.startswith(".core"):
            core = int(s.split()[1])
            out[core] = 0
        elif core is not None and s.startswith("        ") and s.strip():
            out[core] += 1
    return out
