"""Generate derived files from code/md/machine.py.

    python code/md/gen.py          write src/md_defs.vh, code/md/machine.json, wiki/ISA_TABLES.md
    python code/md/gen.py --check  fail if any generated file is out of date (used by tests)
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import machine as m  # noqa: E402


def _ident(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", name).upper()


def verilog() -> str:
    o = ["// GENERATED by code/md/gen.py from code/md/machine.py. Do not edit.", "`ifndef MD_DEFS_VH", "`define MD_DEFS_VH", ""]
    for k in ["N_CORES", "N_ENGINES", "N_BEATGENS", "N_SHIFTERS", "N_COUNTERS", "N_LFSRS", "N_ACC_REGS", "N_PTRS",
              "N_FLAGS", "PROG_WORDS", "DATA_BYTES", "BG_WIDTH", "N_IN_PINS", "N_OUT_PINS", "N_OE_PINS", "VERSION"]:
        o.append(f"localparam integer MD_{k} = {getattr(m, k)};")
    o.append("")
    for f in m.FIELDS:
        o.append(f"localparam integer F_{_ident(f.name)}_LSB = {f.lsb};")
        o.append(f"localparam integer F_{_ident(f.name)}_W = {f.width};")
    o.append("")
    for k, v in m.JMODES.items():
        o.append(f"localparam [1:0] JM_{_ident(k)} = 2'd{v};")
    for k, v in m.GUARDS.items():
        o.append(f"localparam [1:0] GD_{_ident(k)} = 2'd{v};")
    o.append("")
    for i, p in enumerate(m.SRC):
        o.append(f"localparam [5:0] S_{_ident(p.name)} = 6'd{i};")
    o.append("")
    for i, p in enumerate(m.DST):
        o.append(f"localparam [5:0] D_{_ident(p.name)} = 6'd{i};")
    o.append("")
    for i, p in enumerate(m.GUARD_CONDS):
        o.append(f"localparam [5:0] G_{_ident(p.name)} = 6'd{i};")
    o.append("")
    for i, n in enumerate(m.TRIGGERS):
        o.append(f"localparam [4:0] T_{_ident(n)} = 5'd{i};")
    o.append("")
    for k, v in m.HOST_MAP.items():
        o.append(f"localparam [15:0] H_{k} = 16'h{v:04X};")
    for tbl, pre in [(m.BG_REGS, "HBG"), (m.ENG_REGS, "HENG"), (m.OUT_REGS, "HOUT"), (m.CTRL_REGS, "HCTRL")]:
        for off, (name, nb) in tbl.items():
            o.append(f"localparam [7:0] {pre}_{_ident(name)} = 8'h{off:02X};  // {nb} byte(s)")
    for off, (name, nb) in m.UNIT_REGS.items():
        o.append(f"localparam [7:0] HUNIT_{_ident(name)} = 8'h{off:02X};  // {nb} byte(s)")
    o += ["", "`endif", ""]
    return "\n".join(o)


def as_json() -> str:
    d = {
        "version": m.VERSION,
        "sizes": {k: getattr(m, k) for k in dir(m) if k.startswith("N_") or k in
                  ("PROG_WORDS", "DATA_BYTES", "BG_WIDTH", "DATA_WIDTH", "INSN_BITS")},
        "fields": {f.name: [f.lsb, f.width] for f in m.FIELDS},
        "jmodes": m.JMODES, "guards": m.GUARDS,
        "src": [p.name for p in m.SRC], "dst": [p.name for p in m.DST],
        "guard_conds": [p.name for p in m.GUARD_CONDS], "triggers": m.TRIGGERS,
        "in_pins": m.IN_PINS, "out_pins": m.OUT_PINS, "host_pins": m.HOST_PINS,
        "host_map": m.HOST_MAP,
        "bg_regs": {f"{k:#04x}": v for k, v in m.BG_REGS.items()},
        "eng_regs": {f"{k:#04x}": v for k, v in m.ENG_REGS.items()},
        "out_regs": {f"{k:#04x}": v for k, v in m.OUT_REGS.items()},
        "unit_regs": {f"{k:#04x}": v for k, v in m.UNIT_REGS.items()},
        "ctrl_regs": {f"{k:#04x}": v for k, v in m.CTRL_REGS.items()},
        "host_readable": m.HOST_READABLE,
    }
    return json.dumps(d, indent=1) + "\n"


def tables() -> str:
    o = ["# ISA tables (generated)", "",
         "Generated by `code/md/gen.py` from `code/md/machine.py`. Do not edit. Semantics: [SPEC.md](SPEC.md).", "",
         "## Instruction word (64 bits)", "", "| Field | Bits | Width |", "|---|---|---|"]
    o += [f"| `{f.name}` | {f.msb}:{f.lsb} | {f.width} |" for f in m.FIELDS]
    o += ["", f"Jump modes: {', '.join(f'`{k}`={v}' for k, v in m.JMODES.items())}. "
          f"Move guards: {', '.join(f'`{k}`={v}' for k, v in m.GUARDS.items())}.", ""]
    for title, lst in [("Source ports", m.SRC), ("Destination ports", m.DST), ("Guard conditions", m.GUARD_CONDS)]:
        o += [f"## {title} ({len(lst)} of 64)", "", "| # | Name | Meaning |", "|---|---|---|"]
        o += [f"| {i} | `{p.name}` | {p.desc} |" for i, p in enumerate(lst)]
        o.append("")
    o += ["## Trigger sources", "", "| # | Name |", "|---|---|"]
    o += [f"| {i} | `{n}` |" for i, n in enumerate(m.TRIGGERS)]
    o += ["", "## Pins", "", "| Index | Input pin | Output pin |", "|---|---|---|"]
    for i in range(max(m.N_IN_PINS, m.N_OUT_PINS)):
        o.append(f"| {i} | {m.IN_PINS[i] if i < m.N_IN_PINS else ''} | {m.OUT_PINS[i] if i < m.N_OUT_PINS else ''} |")
    o += ["", "Host link: " + ", ".join(f"{k} = {v}" for k, v in m.HOST_PINS.items()) + ".", "",
          "## Host address map", "", "| Block | Base |", "|---|---|"]
    o += [f"| {k} | 0x{v:04X} |" for k, v in m.HOST_MAP.items()]
    for title, tbl in [("Beat generator registers (+0x20 per generator)", m.BG_REGS),
                       ("Engine registers (+0x20 per engine)", m.ENG_REGS),
                       ("Output cell registers (+0x08 per cell)", m.OUT_REGS),
                       ("Unit registers", m.UNIT_REGS), ("Control registers", m.CTRL_REGS)]:
        o += ["", f"### {title}", "", "| Offset | Name | Bytes |", "|---|---|---|"]
        o += [f"| 0x{k:02X} | {n} | {b} |" for k, (n, b) in tbl.items()]
    return "\n".join(o) + "\n"


OUTPUTS = {
    ROOT / "src/md_defs.vh": verilog,
    ROOT / "code/md/machine.json": as_json,
    ROOT / "wiki/ISA_TABLES.md": tables,
}


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, fn in OUTPUTS.items():
        text = fn()
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print("wrote", path.relative_to(ROOT))
    if stale:
        print("stale generated files:", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
