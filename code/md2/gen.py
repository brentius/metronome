"""Generate derived files from code/md2/machine.py (Metronome v2).

    python code/md2/gen.py          write code/md2/md2_defs.vh, code/md2/machine.json, wiki/ISA_TABLES_V2.md
    python code/md2/gen.py --check  fail if any generated file is out of date (used by tests)

The Verilog header moves to src/ when the v2 RTL replaces v1 there (D22).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import machine as m  # noqa: E402

SIZES = ["N_CORES", "N_LINES", "N_THREADS", "N_STREAMS", "N_SHIFTERS", "N_COUNTERS", "N_LFSRS", "N_ACC_REGS",
         "N_PTRS", "N_FLAGS", "PROG_WORDS", "DATA_BYTES", "BG_WIDTH", "OSYM_BITS", "ISYM_BITS", "N_SAMPLES",
         "LUT_IN_BITS", "PIN_LUT_IN_BITS", "STREAM_ADDR_BITS", "STREAM_LEN_BITS", "N_IN_PINS", "N_OUT_PINS",
         "N_OE_PINS", "VERSION"]


def _ident(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", name).upper()


def verilog() -> str:
    o = ["// GENERATED by code/md2/gen.py from code/md2/machine.py. Do not edit.",
         "`ifndef MD2_DEFS_VH", "`define MD2_DEFS_VH", ""]
    o += [f"localparam integer MD_{k} = {getattr(m, k)};" for k in SIZES]
    o.append("")
    for f in m.FIELDS:
        o.append(f"localparam integer F_{_ident(f.name)}_LSB = {f.lsb};")
        o.append(f"localparam integer F_{_ident(f.name)}_W = {f.width};")
    o.append("")
    o += [f"localparam [1:0] JM_{_ident(k)} = 2'd{v};" for k, v in m.JMODES.items()]
    o += [f"localparam [1:0] GD_{_ident(k)} = 2'd{v};" for k, v in m.GUARDS.items()]
    o.append("")
    o += [f"localparam [5:0] S_{_ident(p.name)} = 6'd{i};" for i, p in enumerate(m.SRC)]
    o.append("")
    o += [f"localparam [5:0] D_{_ident(p.name)} = 6'd{i};" for i, p in enumerate(m.DST)]
    o.append("")
    o += [f"localparam [5:0] G_{_ident(p.name)} = 6'd{i};" for i, p in enumerate(m.GUARD_CONDS)]
    o.append("")
    o.append("// jump condition j selects guard JG_<j>; JG_MAP packs the 32 guard indices, entry j in bits 6j+5:6j")
    o.append(f"localparam [{6 * 32 - 1}:0] JG_MAP = {{" + ", ".join(
        f"6'd{m.GUARD_ID[n] if n else 0}" for n in reversed(m.JUMP_GUARDS + [None] * (32 - len(m.JUMP_GUARDS))))
        + "};")
    o.append("")
    o += [f"localparam [4:0] T_{_ident(n)} = 5'd{i};" for i, n in enumerate(m.TRIGGERS)]
    o += ["", "`endif", ""]
    return "\n".join(o)


def as_json() -> str:
    d = {
        "version": m.VERSION,
        "sizes": {k: getattr(m, k) for k in SIZES + ["DATA_WIDTH", "INSN_BITS", "N_MOVES", "LFSR_WIDTH"]},
        "fields": {f.name: [f.lsb, f.width] for f in m.FIELDS},
        "jmodes": m.JMODES, "guards": m.GUARDS,
        "src": [p.name for p in m.SRC], "dst": [p.name for p in m.DST],
        "guard_conds": [p.name for p in m.GUARD_CONDS], "jump_guards": m.JUMP_GUARDS,
        "triggers": m.TRIGGERS, "write_groups": m.WRITE_GROUPS,
        "in_pins": m.IN_PINS, "out_pins": m.OUT_PINS, "host_pins": m.HOST_PINS,
        "config_blocks": {b: {"fields": f, "instances": n} for b, (f, n) in m.CONFIG_BLOCKS.items()},
        "config_bits": m.CONFIG_BITS, "config_bits_total": m.CONFIG_BITS_TOTAL,
    }
    return json.dumps(d, indent=1) + "\n"


def tables() -> str:
    o = ["# ISA tables, Metronome v2 (generated)", "",
         "Generated by `code/md2/gen.py` from `code/md2/machine.py`. Do not edit. Semantics: SPEC v2 (in progress); "
         "until it exists, `BOTS/PLANS/V2_DESIGN.md` section 4. v1 tables: [ISA_TABLES.md](ISA_TABLES.md).", "",
         "## Instruction word (64 bits)", "", "| Field | Bits | Width |", "|---|---|---|"]
    o += [f"| `{f.name}` | {f.msb}:{f.lsb} | {f.width} |" for f in m.FIELDS]
    o += ["", f"Jump modes (on `jcond`): {', '.join(f'`{k}`={v}' for k, v in m.JMODES.items())}. "
          f"Move guards (on `cond`): {', '.join(f'`{k}`={v}' for k, v in m.GUARDS.items())}.", ""]
    for title, lst in [("Source ports", m.SRC), ("Destination ports", m.DST), ("Guard conditions", m.GUARD_CONDS)]:
        o += [f"## {title} ({len(lst)} of 64)", "", "| # | Name | Meaning |", "|---|---|---|"]
        o += [f"| {i} | `{p.name}` | {p.desc} |" for i, p in enumerate(lst)]
        o.append("")
    o += [f"## Jump conditions ({len(m.JUMP_GUARDS)} of 32)", "", "| jcond | Guard | Guard index |", "|---|---|---|"]
    o += [f"| {j} | `{n}` | {m.GUARD_ID[n]} |" for j, n in enumerate(m.JUMP_GUARDS)]
    o += ["", f"## Trigger sources ({len(m.TRIGGERS)} of 32)", "", "| # | Name |", "|---|---|"]
    o += [f"| {i} | `{n}` |" for i, n in enumerate(m.TRIGGERS)]
    o += ["", "## Write groups", "", "| Group | Destinations |", "|---|---|"]
    o += [f"| `{g}` | {', '.join(f'`{d}`' for d in ds)} |" for g, ds in m.WRITE_GROUPS.items()]
    o += ["", f"## Latch configuration inventory ({m.CONFIG_BITS_TOTAL} bits)", "",
          "| Block | Instances | Fields (bits) | Bits |", "|---|---|---|---|"]
    for b, (f, n) in m.CONFIG_BLOCKS.items():
        o.append(f"| {b} | {n} | {', '.join(f'{k} {v}' for k, v in f.items())} | {m.CONFIG_BITS[b]} |")
    o += ["", "## Pins", "", "| Index | Input pin | Output pin |", "|---|---|---|"]
    for i in range(max(m.N_IN_PINS, m.N_OUT_PINS)):
        o.append(f"| {i} | {m.IN_PINS[i] if i < m.N_IN_PINS else ''} | {m.OUT_PINS[i] if i < m.N_OUT_PINS else ''} |")
    o += ["", "Host link: " + ", ".join(f"{k} = {v}" for k, v in m.HOST_PINS.items()) + "."]
    return "\n".join(o) + "\n"


OUTPUTS = {
    HERE / "md2_defs.vh": verilog,
    HERE / "machine.json": as_json,
    ROOT / "wiki/ISA_TABLES_V2.md": tables,
}


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, fn in OUTPUTS.items():
        text = fn()
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path))
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print("wrote", path.relative_to(ROOT))
    if stale:
        print("stale generated files:", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
